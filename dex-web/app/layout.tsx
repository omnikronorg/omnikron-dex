import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Providers from "@/components/Providers";
import { getNetworkList } from "@/lib/networks";
import { getTokenListAll } from "@/lib/tokens";
import { getChainConfigList } from "@/config/chainConfig";
import { connection } from "next/server";
import { ensureDataLoaded } from "@/lib/dataLoaders.server";

// cacheComponents: this layout depends on runtime data (MongoDB via dataLoaders). 
// Allowing blocking at request time prevents prerendering errors.
export const instant = false;

const geistSans = Geist({
    variable: "--font-geist-sans",
    subsets: ["latin"],
});

const geistMono = Geist_Mono({
    variable: "--font-geist-mono",
    subsets: ["latin"],
});

export const metadata: Metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {

    // Check in request-time, when the boot (register of instrumentation) already
    // fill — or when the ensureDataLoaded() query the Mongo if needed.
    await connection();
    await ensureDataLoaded();

    // Read the server-side in-memory caches (populated at boot by
    // instrumentation.ts) and hand them to Providers so the client can hydrate
    // the same caches before rendering — keeping SSR and client output identical.
    const initialData = {
        networks: getNetworkList(),
        tokens: getTokenListAll(),
        chainConfigs: getChainConfigList(),
    };

    return (
        <html
            lang="en"
            className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
        >
            <body className="min-h-screen flex flex-col">
                <Providers initialData={initialData}>
                  {children}
                </Providers>

            </body>
        </html>
    );
}
